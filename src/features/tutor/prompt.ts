function list(items: string[], fallback: string) {
  return items.length ? items.map((item) => `- ${item}`).join("\n") : `- ${fallback}`;
}

function formulas(unit: LearningUnit) {
  if (!unit.formulas.length) return "- 별도로 제공된 공식 없음";
  return unit.formulas
    .map((formula) => `- ${formula.name}: ${formula.expression} — ${formula.explanation}`)
    .join("\n");
}

function textbookContext(unit: LearningUnit) {
  const schoolPublisher = unit.schoolPublisherName ?? unit.publisherName;
  const lines = [
    `- 학교 채택 교과서 출판사: ${schoolPublisher}`,
    `- 현재 단원 데이터의 구성 기준: ${unit.publisherName}`,
  ];

  if (schoolPublisher !== unit.publisherName) {
    lines.push(`- 적용 주의: 학교 채택본은 ${schoolPublisher}이지만 현재 세부 단원 데이터는 ${unit.publisherName} 기준입니다. 국가 교육과정의 공통 개념만 설명하고, ${schoolPublisher} 교과서의 단원 순서·표현·예제를 확인한 것처럼 말하지 마세요.`);
  } else {
    lines.push("- 적용 주의: 출판사와 과목 채택 정보는 확인되었지만, 제공되지 않은 본문·활동·쪽수·시험 범위까지 알고 있다고 가정하지 마세요.");
  }

  return lines.join("\n");
}

