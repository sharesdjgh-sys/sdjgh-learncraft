const CURATED_TERMS = new Map<string, readonly string[]>(
  CURATED_SOURCE_TERMS.map(([source, terms]) => [canonicalTerm(source), terms] as const),
);

const GRADE_TWO_TERMS = new Map<string, readonly string[]>(
  GRADE_TWO_TOPIC_TERMS.map(([source, terms]) => [canonicalTerm(source), terms] as const),
);

export function mathVocabularyTerms(topicTitle: string, keyPoints: string[]): string[] {
  const reviewedTopicTerms = GRADE_TWO_TERMS.get(canonicalTerm(topicTitle));
  if (reviewedTopicTerms) return [...reviewedTopicTerms];

  const terms: string[] = [];
  const seen = new Set<string>();

  for (const candidate of [topicTitle, ...keyPoints]) {
    const curated = CURATED_TERMS.get(canonicalTerm(candidate));
    if (!curated) continue;

    for (const term of curated) {
      const key = canonicalTerm(term);
      if (!key || seen.has(key)) continue;
      seen.add(key);
      terms.push(term);
    }
  }

  return terms;
}
