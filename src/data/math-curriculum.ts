function buildTutorInstructions(
  course: CourseSeed,
  chapter: ChapterSeed,
  section: SectionSeed,
  topic: TopicSeed,
) {
  const prerequisites = topic.prerequisites?.length
    ? topic.prerequisites.join(", ")
    : "현재 주제에 필요한 바로 앞 개념";
  const excluded = topic.scopeExcluded?.length
    ? topic.scopeExcluded.join(", ")
    : "학생이 요청하지 않은 대학 수준의 정의와 증명";

  return `현재 지도 범위는 ${course.title} > ${chapter.title} > ${section.title} > ${topic.title}입니다.
- 학습 목표: ${topic.goal}.
- 선수 개념 확인: ${prerequisites}.
- 반드시 연결할 핵심: ${topic.keyPoints.join(", ")}.
- 먼저 확인할 대표 오개념: ${topic.commonMistakes.join(" / ")}.
- 범위에서 제외: ${excluded}.
- 풀이에서는 사용한 정의나 공식의 적용 조건을 먼저 밝히고, 핵심 계산을 생략하지 않으며, 마지막에 위 오개념 중 하나를 스스로 점검하게 합니다.`;
}

function buildMathUnits() {
  return courses.flatMap((course, courseIndex) => {
    let topicIndex = 0;
    return course.chapters.flatMap((chapter, chapterIndex) => (
      chapter.sections.flatMap((section, sectionIndex) => (
        section.topics.map((topic, topicIndexInSection) => {
          topicIndex += 1;
          const topicNumber = String(topicIndex).padStart(10, "0");
          const unit: LearningUnit = {
            id: `10000000-0000-4000-8000-${String(courseIndex + 1).padStart(2, "0")}${topicNumber}`,
            code: `${course.code}-${String(chapterIndex + 1).padStart(2, "0")}-${String(sectionIndex + 1).padStart(2, "0")}-${String(topicIndexInSection + 1).padStart(2, "0")}`,
            title: topic.title,
            subjectCode: "MATH",
            subjectTitle: "수학",
            courseCode: course.code,
            courseTitle: course.title,
            courseCategory: course.category,
            courseOrder: course.order,
            chapterTitle: chapter.title,
            chapterOrder: chapterIndex + 1,
            sectionTitle: section.title,
            sectionOrder: sectionIndex + 1,
            topicOrder: topicIndexInSection + 1,
            grade: course.grade,
            recommendedGrades: course.recommendedGrades,
            curriculum: "2022 개정",
            publisherCode: course.publisherCode ?? "VISANG",
            publisherName: course.publisherName ?? "비상교육",
            schoolAdopted: course.schoolAdopted,
            schoolPublisherName: course.schoolPublisherName,
            sourceUrl: course.sourceUrl,
            summary: `${topic.goal}.`,
            keyPoints: topic.keyPoints,
            formulas: topic.formulas ?? [],
            examples: [{
              title: "교과서식 학습 순서",
              body: topic.example ?? `${topic.keyPoints[0]}부터 확인하고, 조건을 식이나 그림으로 바꾼 뒤 결과를 검산합니다.`,
            }],
            recommendedQuestions: [
              `${topic.title} 개념을 처음 배우는 학생도 이해하게 설명해 주세요.`,
              `${topic.commonMistakes[0]} 실수를 하지 않는 방법을 예제로 보여 주세요.`,
              `${topic.title} 표준 난이도 확인 문제를 한 개 내주세요.`,
            ],
            keywords: Array.from(new Set([topic.title, section.title, chapter.title, ...topic.keyPoints])),
            prerequisites: topic.prerequisites ?? [],
            commonMistakes: topic.commonMistakes,
            scopeExcluded: topic.scopeExcluded ?? ["요청하지 않은 대학 수준의 개념"],
            assessmentTags: [course.code, chapter.title, section.title, topic.title],
            tutorInstructions: buildTutorInstructions(course, chapter, section, topic),
          };
          return unit;
        })
      ))
    ));
  });
}

