/**
 * 한반도·만주 영역 보정입니다. 공개 자료(historical-basemaps)는 한국사 부분에 오류가 많아
 * (예: 700년에 멸망한 고구려·백제가 남음, 1279~1400년 한반도가 몽골 제국 영토, 5세기 요동이 북위 영토)
 * 교과서의 시기별 대표 지도를 참고해 대략적인 영역을 다시 그립니다.
 *
 * - 좌표는 [경도, 위도]입니다. 바다 쪽은 넉넉하게 그려도 됩니다(화면에서 육지 모양으로 잘라 그림).
 * - polities는 앞에 적은 나라가 먼저 자리를 차지합니다. 뒤의 나라는 앞 나라와 겹치는 부분이 빠지므로
 *   맨 뒤 나라를 넉넉하게 그려 빈틈을 메웁니다.
 * - "peninsula"는 현대 지도(1:1천만)의 한반도(북한+대한민국, 울릉도·독도 포함)입니다.
 * - 보정한 시기에는 한반도에서 원래 자료의 영역을 모두 지우고(clearPeninsula), 보정 영역과 겹치는 원래 자료도 지웁니다.
 */
